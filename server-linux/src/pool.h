/*
 * pool.h —— 线程池对外契约（规划 §2.3，S2 实现）
 *
 * 模型：固定 nthreads 个工作线程 + 有界任务队列（互斥锁 + 条件变量，
 *       经典生产者-消费者）。生产者 = select 主循环，消费者 = 工作线程。
 *
 * 任务 = 一个函数指针 + 一个参数指针。线程池只搬运这两个指针，不解释参数
 * 含义，也不负责释放：任务体（fn）执行完必须自行释放 arg 指向的内存。
 *
 * 背压：队列满时 pool_submit 阻塞等待，直到有工作线程取走任务。这是刻意选择
 * 的——主线程停摆会让接收窗口关闭，把压力反弹给客户端；而"丢任务"丢的是已经
 * 收下来的业务数据，且现场难以察觉。
 *
 * 锁序（规划 S2 任务 5）：任务体在工作线程内执行时**不持有池锁**，因此任务里
 * 可以安全地再调用 net_send / session_*（它们的锁序是 会话表锁 → 发送锁）。
 */
#ifndef POOL_H
#define POOL_H

/* 创建 nthreads 个工作线程（上限 POOL_THREADS，队列容量 POOL_QUEUE_SIZE）。
 * 进程生命周期内调用一次，启动后即可投递；线程随进程退出，没有销毁接口。
 * 失败时打印错误日志，实际的线程数记在日志里。 */
void pool_init(int nthreads);

/* 把任务投递给线程池（队列满时阻塞等待空位，见头文件顶部说明）。
 * fn 由某个工作线程调用，arg 原样传回 fn。fn 为 NULL 或池未初始化时
 * 打印错误日志并直接返回（不阻塞）。 */
void pool_submit(void (*fn)(void *), void *arg);

#endif /* POOL_H */
